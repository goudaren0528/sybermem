#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const entry = resolve(root, "packages/opencode-plugin/src/index.ts")
const outfile = resolve(root, "packages/opencode-plugin/sybermem.ts")
const checkOnly = process.argv.includes("--check")

const result = await Bun.build({
  entrypoints: [entry],
  target: "bun",
  format: "esm",
  external: ["@opencode-ai/plugin"],
  sourcemap: "none",
  minify: false,
  write: false,
})

if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}

const [output] = result.outputs
if (!output) {
  console.error("Bun produced no OpenCode plugin bundle output")
  process.exit(1)
}
const bundled = await output.text()
const header = [
  "/**",
  " * SyberMem OpenCode Plugin (generated bundle)",
  " * Source: packages/opencode-plugin/src/index.ts",
  " * Regenerate with: bun scripts/build-opencode-plugin.mjs",
  " * Do not edit this file by hand; installers copy this single file to ~/.config/opencode/plugins/sybermem.ts.",
  " */",
  "",
].join("\n")
await mkdir(dirname(outfile), { recursive: true })
const nextBundle = `${header}${bundled}`
if (checkOnly) {
  const current = await readFile(outfile, "utf-8").catch(() => "")
  if (current !== nextBundle) {
    console.error("packages/opencode-plugin/sybermem.ts is stale; run bun scripts/build-opencode-plugin.mjs")
    process.exit(1)
  }
} else {
  await writeFile(outfile, nextBundle, "utf-8")
}
