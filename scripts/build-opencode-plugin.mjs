#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const expectedBun = (await readFile(resolve(root, ".bun-version"), "utf-8")).trim()
if (Bun.version !== expectedBun) {
  console.error(`OpenCode bundles require Bun ${expectedBun} from .bun-version; running ${Bun.version}. Use the pinned version before building or checking.`)
  process.exit(1)
}
const tui = process.argv.includes("--tui")
const packageTarget = process.argv.includes("--package")
const v1 = process.argv.includes("--v1")
if (v1 && (tui || packageTarget)) throw new Error("--v1 cannot be combined with --tui or --package")
const source = v1 ? "v1" : tui ? "tui" : "index"
const entry = resolve(root, `packages/opencode-plugin/src/${source}.ts`)
const outfile = resolve(root, `packages/opencode-plugin/${packageTarget ? `dist-v2/${tui ? "tui" : "server"}.js` : v1 ? "sybermem-v1.ts" : `${tui ? "sybermem-tui" : "sybermem"}.ts`}`)
const checkOnly = process.argv.includes("--check")
const buildFlags = `${v1 ? " --v1" : ""}${packageTarget ? " --package" : ""}${tui ? " --tui" : ""}`
const normalizeNewlines = (text) => text.replace(/\r\n/g, "\n")

const result = await Bun.build({
  entrypoints: [entry],
  target: "bun",
  format: "esm",
  external: ["@opencode-ai/plugin"],
  sourcemap: "none",
  minify: false,
  write: false,
})

if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}

const [output] = result.outputs
if (!output) {
  console.error("Bun produced no OpenCode plugin bundle output")
  process.exit(1)
}
const bundled = await output.text()
const header = [
  "/**",
  " * SyberMem OpenCode Plugin (generated bundle)",
  ` * Source: packages/opencode-plugin/src/${source}.ts`,
  ` * Regenerate with: bun scripts/build-opencode-plugin.mjs${buildFlags}`,
  ` * Do not edit this file by hand; ${v1 ? "V1 compatibility plugin." : tui ? "deploy as the TUI companion to the server bundle." : packageTarget ? "V2 server package entrypoint." : "V2 server compatibility artifact."}`,
  " */",
  "",
].join("\n")
const nextBundle = `${header}${bundled}`
if (checkOnly) {
  const current = await readFile(outfile, "utf-8").catch(() => "")
  if (normalizeNewlines(current) !== normalizeNewlines(nextBundle)) {
    console.error(`${outfile} is stale; run bun scripts/build-opencode-plugin.mjs${buildFlags}`)
    process.exit(1)
  }
} else {
  await mkdir(dirname(outfile), { recursive: true })
  await writeFile(outfile, nextBundle, "utf-8")
}
if (packageTarget) {
  const manifest = resolve(root, "scripts/opencode-v2-package.json")
  const installed = resolve(root, "packages/opencode-plugin/dist-v2/package.json")
  const expected = await readFile(manifest, "utf-8")
  if (checkOnly) {
    if (normalizeNewlines(await readFile(installed, "utf-8").catch(() => "")) !== normalizeNewlines(expected)) {
      console.error(`${installed} is stale; regenerate with --package`)
      process.exit(1)
    }
  } else {
    await writeFile(installed, expected, "utf-8")
  }
}
